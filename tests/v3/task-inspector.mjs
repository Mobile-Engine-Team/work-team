import {captureTaskControls} from "./layout-geometry.mjs";
import { resolve } from "node:path";
import assert from "node:assert/strict";

export async function verifyTaskInspector(page,output) {
  const button = (scope,name) => scope.getByRole("button",{name,exact:true});
  const inspector = page.locator(".v3-issue-inspector");
  const due = button(inspector,"详情截止日期");
  const originalDue = await due.innerText();
  assert.match(originalDue,/^\d{4}-\d{2}-\d{2}$/);
  assert.equal(await inspector.getByRole("combobox",{name:"负责人"}).innerText().then(t=>t.includes("团队成员")),false);
  const calendar = page.locator(".v3-date-calendar");
  const enter = async (label,value) => {
    const input=calendar.getByRole("textbox",{name:"输入"+label});
    await input.fill(value);
    await input.press("Enter");
  };
  await due.click();
  await enter("详情截止日期","2097-02-29");
  await calendar.getByText("请输入有效日期 YYYY-MM-DD").waitFor();
  await page.keyboard.press("Escape");
  await calendar.waitFor({state:"hidden"});
  assert.equal(await due.innerText(),originalDue);
  await due.click();
  await enter("详情截止日期","2096-02-29");
  await due.filter({hasText:"2096-02-29"}).waitFor();
  await page.reload();
  await due.filter({hasText:"2096-02-29"}).waitFor();
  await button(inspector,"更多属性").click();
  const tags=inspector.getByRole("textbox",{name:"详情任务标签"});
  const originalTags=await tags.inputValue();
  await tags.fill("仅取消的标签");await tags.press("Escape");assert.equal(await tags.inputValue(),originalTags);
  await tags.fill("交付检查，现场记录");await tags.press("Enter");
  await page.waitForFunction(()=>document.querySelector('[aria-label="详情任务标签"]')?.value.includes(", "));
  await page.reload();await button(inspector,"更多属性").click();
  assert.deepEqual((await tags.inputValue()).split(", ").sort(),["交付检查","现场记录"].sort());
  await tags.fill(originalTags);await tags.press("Enter");
  await button(inspector,"详情开始日期").click();
  await enter("详情开始日期","2096-03-01");
  await calendar.getByText("截止日期不能早于开始日期").waitFor();
  await page.keyboard.press("Escape");
  await button(inspector,"收起属性").click();
  await due.click();
  await button(calendar,"下个月").click();
  await button(calendar,"上个月").click();
  await button(calendar,"2096-02-28").click();
  await due.filter({hasText:"2096-02-28"}).waitFor();
  await due.click();
  await button(calendar,"清除日期").click();
  await due.filter({hasText:"未设置"}).waitFor();
  await page.reload();
  await due.filter({hasText:"未设置"}).waitFor();
  await due.click();
  await enter("详情截止日期",originalDue);
  await due.filter({hasText:originalDue}).waitFor();
  assert.deepEqual(await inspector.locator(":scope>details>summary").allInnerTexts(),["唤醒与提醒","执行日志"]);
  const details = inspector.locator(":scope>details").last();
  await details.locator(":scope>summary").click();
  await details.getByRole("region",{name:"任务产物与输入材料"}).waitFor();
  await details.locator(":scope>summary").click();

  const address = page.url();
  await button(inspector,"发起会话").click();
  const side = inspector.getByRole("dialog",{name:"临时 Work 会话"});
  await side.getByText("实现上传重试去重",{exact:true}).waitFor();
  const rail=page.locator("#v3-task-detail-rail");
  const box=await rail.boundingBox();
  assert.deepEqual([box.x,box.y,box.width,box.height],[1020,88,420,812]);
  await captureTaskControls(page,output,"side-chat");
  await page.screenshot({path:resolve(output,"demo-side-chat.png"),animations:"disabled"});
  const handle=rail.getByRole("separator",{name:"调整任务聊天宽度"});
  await handle.press("ArrowLeft");
  assert.equal((await rail.boundingBox()).width,432);
  const prompt = side.getByRole("textbox");
  await prompt.fill("侧聊口令青松");
  await prompt.press("Enter");
  await side.locator("article").first().getByText(/【Mock】/).waitFor();
  await prompt.fill("刚才的口令是什么");
  await prompt.press("Enter");
  await side.locator("article").nth(1).locator("p").filter({hasText:"青松"}).waitFor();
  const workspace=side.getByRole("combobox",{name:"工作空间"});
  await workspace.selectOption({label:"移动端弱网上传"});
  await side.getByRole("combobox",{name:"执行权限"}).selectOption("full");
  await button(side,"提及协作者").click();
  await side.getByText("临时会话仅限你与 Work 讨论").waitFor();
  await button(side,"收起候选").click();
  const file={name:"临时测试.txt",mimeType:"text/plain",buffer:Buffer.from("独立侧聊天蓝材料")};
  const upload=side.getByLabel("选择临时附件");
  await upload.setInputFiles(file);
  await button(side,"移除 "+file.name).click();
  assert.equal(await button(side,"发送").isDisabled(),true);
  await upload.setInputFiles(file);await button(side,"发送").click();
  const fileTurn=side.locator("article").nth(2);
  await fileTurn.locator("p").filter({hasText:"天蓝材料"}).waitFor();
  const downloadPromise=page.waitForEvent("download");
  await button(fileTurn,file.name).click();
  const stream=await (await downloadPromise).createReadStream();
  const chunks=[];for await(const chunk of stream) chunks.push(chunk);
  assert.deepEqual(Buffer.concat(chunks),file.buffer);
  assert.equal(page.url(),address);
  await button(side,"关闭").click();
  await button(inspector,"发起会话").click();
  assert.equal((await rail.boundingBox()).width,432);
  assert.equal(await side.locator("article").count(),0);
  assert.equal(await workspace.inputValue(),"");
  assert.equal(await side.getByRole("combobox",{name:"执行权限"}).inputValue(),"default");
  await handle.press("ArrowRight");
  await button(side,"关闭").click();
  assert.equal(page.url(),address);
}
