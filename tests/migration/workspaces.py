import re
from playwright.sync_api import expect

from support import btn, click, close, combo, dialog, field, login, space, sql


def register(p, name, password):
    account = field(p, '账号')
    expect(account).to_be_focused()
    account.fill(name)
    click(p, '没有账号？注册账号')
    expect(account).to_have_value(name)
    passwords = p.locator('input[type=password]')
    passwords.first.fill(password)
    passwords.last.fill(password+'-different')
    p.locator('form button').click()
    expect(p.get_by_role('alert')).to_contain_text('两次输入的密码不一致')
    passwords.last.fill(password)
    p.locator('form button').click()
    expect(p.get_by_role('combobox', name='工作区')).to_contain_text('个人工作区')

def accounts(r):
    a,b=r.a,r.b
    expect(field(a,'账号')).to_be_focused()
    expect(a.locator('input[type=password]')).to_have_value('')
    r.ev.record(a,'OS-01 AU-01','新测试资料打开产品','中文登录页，账号聚焦，密码为空。','01')
    for p,name in [(a,r.ua),(b,r.ub)]:
        register(p,name,r.password)
    r.ev.record(a,'AU-02 AU-03 WB-01','A/B 分别注册，先提交两次不同的密码','两端都提示密码不一致，改正后分别进入自己的个人工作台。','02')
    click(b,'退出账号')
    field(b,'账号').fill(r.ub)
    b.locator('input[type=password]').fill('invalid-verification-password')
    b.locator('form button').click()
    expect(b.get_by_role('alert')).to_contain_text('登录未完成')
    login(b,r.ub,r.password)
    r.ev.record(b,'AU-04 AU-05','B 退出后用错误密码和正确密码依次登录','错误时停在登录页，正确密码回个人区。')

def workspace(r):
    a=r.a
    click(a,'新建工作区')
    d=dialog(a)
    name,slug=field(d,'名称'),field(d,'工作区地址')
    expect(name).to_be_focused()
    create=btn(d,'创建')
    expect(create).to_be_disabled()
    r.ev.record(a,'WS-03','打开新建工作区','名称默认聚焦，地址空白，创建禁用。','03')
    name.fill('  ')
    slug.fill('bad space!')
    expect(create).to_be_disabled()
    name.fill('基线协作组')
    expect(create).to_be_enabled()
    r.ev.record(a,'WS-04','空白名称改为非空，地址含空格','名称空白禁用，填写名称后允许提交非法地址。')
    for how,id in [('Esc','WS-05'),('叉号','WS-06'),('遮罩','WS-07')]:
        if how=='Esc':
            a.keyboard.press('Escape')
        elif how=='叉号':
            click(d,'Close')
        else:
            a.mouse.click(12,180)
        expect(d).not_to_be_visible()
        click(a,'新建工作区')
        expect(name).to_have_value('基线协作组')
        expect(slug).to_have_value('bad space!')
        r.ev.record(a,id,'带输入经'+how+'关闭后重开','名称及地址都保留。')
    click(d,'创建')
    expect(d).to_contain_text('操作未完成')
    r.ev.record(a,'WS-08','提交含空格及标点的地址','弹窗报告失败，两个字段保留。','04')
    slug.fill(r.slug)
    click(d,'创建')
    expect(d).not_to_be_visible()
    expect(a.get_by_role('combobox',name='工作区')).to_contain_text('基线协作组')
    r.ev.record(a,'WS-09','创建唯一地址团队','弹窗关闭，A 的工作区选择器落在新团队。','05')
    click(a,'新建工作区')
    expect(name).to_have_value('基线协作组')
    expect(slug).to_have_value(r.slug)
    name.fill('重名复验')
    click(d,'创建')
    expect(d).to_contain_text('操作未完成')
    assert sql("select count(*) from workspace where slug=:'s';",s=r.slug)=='1'
    r.ev.record(a,'WS-10','同地址、不同名称再次提交','弹窗报错，数据库仅有一份该地址。','06')
    close(a)
    a.reload()

