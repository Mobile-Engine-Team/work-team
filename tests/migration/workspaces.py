def invite(r):
    a,b=r.a,r.b
    click(a,'成员与智能体')
    click(a,'邀请成员')
    expect(btn(dialog(a),'保存')).to_be_disabled()
    dialog(a).get_by_role('textbox').fill(r.ub)
    click(dialog(a),'保存')
    toast=b.locator('.team-invite-toast')
    expect(toast).to_contain_text('基线协作组',timeout=18000)
    r.ev.record(b,'IN-01 IN-02','A 邀请 B，B 留在个人区','B 在其个人区收到团队邀请和接受/稍后处理操作。','09')
    click(b,'稍后处理')
    expect(toast).not_to_be_visible()
    b.reload()
    expect(toast).to_be_visible(timeout=18000)
    r.ev.record(b,'IN-03','先稍后处理再刷新','未接受的邀请重新出现。')
    click(toast,re.compile('接受'))
    expect(toast).not_to_be_visible()
    expect(b.get_by_role('combobox',name='工作区')).to_contain_text('基线协作组')
    click(b,'成员与智能体')
    expect(b.get_by_text(r.ua,exact=True).first).to_be_visible()
    expect(btn(b,'邀请成员')).not_to_be_visible()
    roles=sql('''select u.name,m.role from workspace w join member m on m.workspace_id=w.id
        join public."user" u on u.id=m.user_id where w.slug=:'s' order by m.role;''',s=r.slug).splitlines()
    assert set(roles)=={r.ua+'|owner',r.ub+'|member'}
    r.ev.business('members',roles)
    r.ev.record(b,'WS-01 IN-04 IN-05 V2-UX-01','B 在个人区接受邀请','接受后自动切到团队，B 见 A 而无邀请按钮，成员表回读 owner 与 member。')

def agents(r):
    a,b=r.a,r.b
    click(a,'连接远程主机')
    expect(dialog(a)).to_be_visible()
    r.ev.record(a,'EP-04','仅打开 SSH 主机表单','可填写连接条件，未连接外部主机。','30')
    close(a)
    click(a,'启用本机执行端')
    expect(btn(a,'停用本机执行端')).to_be_visible(timeout=30000)
    click(a,'新建智能体')
    d=dialog(a)
    combo(d,'选择执行端',re.compile('Codex',re.I))
    expect(btn(d,'保存')).to_be_disabled()
    click(d,'模型（可选）')
    a.get_by_placeholder('搜索模型名称或 ID').fill('baseline-model')
    click(a,re.compile('baseline-model'))
    expect(btn(d,'模型（可选）')).to_contain_text('baseline-model')
    combo(d,'选择执行端',re.compile('Pi',re.I))
    expect(btn(d,'模型（可选）')).not_to_contain_text('baseline-model')
    field(d,'名称').fill('复验助手')
    field(d,'角色指令').fill('归纳测试记录')
    click(d,'保存')
    expect(d).not_to_be_visible()
    b.reload()
    b.get_by_role('tab',name=re.compile('团队智能体')).click()
    expect(b.get_by_text('复验助手',exact=True)).to_have_count(0)
    r.ev.record(a,'EP-01 AG-04 AG-05 AG-06 AG-07','开启本机受控执行端，Codex 手输模型后切 Pi，私有保存','名称+端才可保存，换端清除自选模型，B 的团队列表无此助手。')
    click(a,re.compile('编辑智能体'))
    expect(field(d,'角色指令')).to_have_value('归纳测试记录')
    d.get_by_role('checkbox').check()
    click(d,'保存')
    expect(d).not_to_be_visible()
    b.reload()
    b.get_by_role('tab',name=re.compile('团队智能体')).click()
    expect(b.get_by_text('复验助手',exact=True)).to_be_visible()
    expect(btn(b,re.compile('编辑智能体'))).not_to_be_visible()
    expect(b.locator('body')).to_contain_text('暂不可获取')
    r.ev.record(b,'AG-08','A 将助手改为团队共享，B 重载','B 见共享助手但无编辑入口，类型为暂不可获取。','10')
    click(a,'停用本机执行端')
    expect(btn(a,'启用本机执行端')).to_be_visible(timeout=15000)
    r.ev.record(a,'EP-02','停止 A 的受控执行端','启用动作恢复；后续离线任务仍可分派给共享助手。')
